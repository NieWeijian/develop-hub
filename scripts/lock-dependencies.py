#!/usr/bin/env python3
"""Regenerate checksum locks in a pinned disposable Python container."""
import email
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import zipfile

root = Path(__file__).resolve().parents[1]
toolchain = json.loads((root / 'deploy/isolated-development/toolchain.lock.json').read_text())
input_path = root / 'requirements/development.in'
key = hashlib.sha256(input_path.read_bytes()).hexdigest()
cache = root / '.cache/dependency-wheels' / key
normalize = lambda name: re.sub('[-_.]+', '-', name).lower()
expected = {normalize(line.split('==')[0]) for line in input_path.read_text().splitlines() if line and not line.startswith('#')}
for abi in ['312', '310']:
    wheels = cache / ('cp' + abi)
    wheels.mkdir(parents=True, exist_ok=True)
    command = ['docker', 'run', '--rm', '--user', f'{os.getuid()}:{os.getgid()}', '--cap-drop=ALL', '--security-opt=no-new-privileges', '--cpus=2', '--memory=4g', '--pids-limit=256', '--mount', f'type=bind,src={root}/requirements,dst=/requirements,readonly', '--mount', f'type=bind,src={wheels},dst=/wheels', '-e', 'HOME=/tmp', toolchain['python_image'], 'python', '-m', 'pip', 'download', '--no-deps', '--only-binary=:all:', '--python-version', '3.' + abi[1:]]
    for platform in ['manylinux_2_35_x86_64', 'manylinux_2_34_x86_64', 'manylinux_2_31_x86_64', 'manylinux_2_28_x86_64', 'manylinux_2_24_x86_64', 'manylinux_2_17_x86_64', 'manylinux2014_x86_64']:
        command += ['--platform', platform]
    subprocess.run(command + ['--implementation', 'cp', '--abi', 'cp' + abi, '-r', '/requirements/development.in', '-d', '/wheels'], check=True)
    records = []
    for wheel in wheels.glob('*.whl'):
        with zipfile.ZipFile(wheel) as archive:
            metadata = email.message_from_bytes(archive.read(next(name for name in archive.namelist() if name.endswith('.dist-info/METADATA'))))
        records.append((metadata['Name'], metadata['Version'], hashlib.sha256(wheel.read_bytes()).hexdigest()))
    if expected != {normalize(row[0]) for row in records} or len(records) != len(expected):
        raise RuntimeError('Missing/duplicate wheel; inspect the isolated download cache')
    name = 'development-linux-amd64.lock' if abi == '312' else 'production-cp310-linux-amd64.lock'
    output = root / 'requirements' / name
    output.write_text('# CPython 3.' + abi[1:] + ', Linux AMD64, glibc 2.35+. Generated by scripts/lock-dependencies.py.\n' + '\n'.join(name + '==' + version + ' --hash=sha256:' + digest for name, version, digest in sorted(records, key=lambda row: normalize(row[0]))) + '\n')
    print('Updated', output)
